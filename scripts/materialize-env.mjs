#!/usr/bin/env node
// Materialise .env.local from the environment Capy injects into this machine.
// Keys come from .env.example; existing values in .env.local win when the
// process environment has nothing for that key, so local-only values survive.
import {readFileSync, writeFileSync, existsSync} from 'node:fs';

const example = readFileSync('.env.example', 'utf8');
const target = process.argv[2] ?? '.env.local';
const existing = existsSync(target) ? readFileSync(target, 'utf8') : '';

function parse(text) {
  const entries = new Map();
  for (const line of text.split(/\r?\n/)) {
    const match = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (match) entries.set(match[1], match[2].trim());
  }
  return entries;
}

const current = parse(existing);
const values = new Map();
const supplied = [];

for (const [name, fallback] of parse(example)) {
  const fromEnv = process.env[name];
  const fromFile = current.get(name);
  if (fromEnv) { values.set(name, fromEnv); supplied.push(name); }
  else if (fromFile !== undefined) values.set(name, fromFile);
  else if (fallback) values.set(name, fallback);
  current.delete(name);
}

for (const [name, value] of current) values.set(name, value);

const quote = value => (/^[^\s"'`#$]*$/.test(value) ? value : JSON.stringify(value));
const body = ['# Generated by scripts/materialize-env.mjs. Never commit this file.'];
let open = false;
for (const line of example.split(/\r?\n/)) {
  if (/^#/.test(line) || line === '') { body.push(line); open = false; continue; }
  const match = line.match(/^([A-Z0-9_]+)=/);
  if (!match) continue;
  const value = values.get(match[1]) ?? '';
  body.push(match[1] + '=' + quote(value));
  open = true;
}
if (open) body.push('');
for (const [name, value] of values) {
  if (!example.includes(name + '=')) body.push(name + '=' + quote(value));
}

writeFileSync(target, body.join('\n').replace(/\n{3,}/g, '\n\n'), {mode: 0o600});
console.log('wrote ' + target + ' with ' + supplied.length + ' values from the environment: ' + supplied.join(' '));
